import AppKit

// The last ten clipboard items, text and images, kept in memory only; items marked secret are skipped

final class Clips {
    enum Item: Equatable {
        case text(String)
        case image(Data, NSSize)
    }

    // newest first, the one on the clipboard now included
    private(set) var items: [Item] = []
    private var current: Item?
    private let pb = NSPasteboard.general
    private var seen: Int
    private var changedAt: Date?
    private var timer: Timer?
    private let secret: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
    private let shotTypes: Set<String> = ["public.png", "Apple PNG pasteboard type", "public.tiff", "NeXT TIFF v4.0 pasteboard type"]
    // Universal Clipboard's mark on a copy from an iPhone, iPad or another Mac
    private let remoteType = "com.apple.is-remote-clipboard"

    init() { seen = pb.changeCount }

    var isOn: Bool { timer != nil }

    // where the item on the clipboard now sits, once a pick has made it other than the first
    var marked: Int? {
        guard let current, let i = items.firstIndex(of: current), i > 0 else { return nil }
        return i
    }

    // what is on the clipboard already joins the list as the current item
    func start() {
        guard timer == nil else { return }
        capture()
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.tick() }
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        items.removeAll()
        current = nil
    }

    // clears all but the item on the clipboard now
    func clear() { items = current.map { [$0] } ?? [] }

    private func tick() {
        let c = pb.changeCount
        if c != seen {
            seen = c
            changedAt = Date()
            return
        }
        guard let at = changedAt, Date().timeIntervalSince(at) >= 0.8 else { return }
        changedAt = nil
        capture()
    }

    private func image() -> Item? {
        guard let data = pb.data(forType: .png) ?? pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return nil }
        return .image(png, NSSize(width: rep.pixelsWide, height: rep.pixelsHigh))
    }

    private func capture() {
        let types = Set(pb.types?.map(\.rawValue) ?? [])
        guard !types.isEmpty, types.isDisjoint(with: secret) else { current = nil; return }
        var item: Item?
        if types.isSubset(of: shotTypes) {
            item = image()
        } else if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            item = .text(String(text.prefix(20000)))
        } else if !types.contains(remoteType) {
            // an image from another device travels only when pasted, so the list keeps the Mac's own
            item = image()
        }
        guard let item else { current = nil; return }
        items.removeAll { $0 == item }
        items.insert(item, at: 0)
        current = item
        if items.count > 10 { items.removeLast(items.count - 10) }
    }

    // a pick from history is Culpmit's own write: the clip goes on the clipboard, the list stays exactly as it was and the
    // pick is the current one
    func copy(_ item: Item) {
        pb.clearContents()
        switch item {
        case .text(let s): pb.setString(s, forType: .string)
        case .image(let data, _): pb.setData(data, forType: .png)
        }
        seen = pb.changeCount
        changedAt = nil
        current = item
    }
}
